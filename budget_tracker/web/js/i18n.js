  function fill(text, vars) {
    return String(text).replace(/\{(\w+)\}/g, function (_, key) {
      return vars && vars[key] != null ? String(vars[key]) : "";
    });
  }

  function t(key, vars) {
    var table = STR[code] || STR.en;
    var text = table[key] != null ? table[key] : STR.en[key];
    if (text == null) return key;
    return fill(text, vars);
  }

  function set(next) {
    code = STR[next] ? next : "en";
    return code;
  }

  function current() {
    return code;
  }

  function has(next) {
    return !!STR[next];
  }

  function dir() {
    var found = LANGS.filter(function (item) { return item.code === code; })[0];
    return found ? found.dir : "ltr";
  }

  function month(index) {
    var list = MONTHS[code] || MONTHS.en;
    return list[index] || MONTHS.en[index] || "";
  }

  function register(meta, months, strings) {
    if (!meta || !meta.code || !strings) return;
    STR[meta.code] = strings;
    if (months && months.length) MONTHS[meta.code] = months;
    var existing = LANGS.filter(function (item) { return item.code === meta.code; })[0];
    if (!existing) LANGS.push({ code: meta.code, name: meta.name, dir: meta.dir || "ltr" });
  }

